func TestBuildRegistry_SubprocessAutoGenerated(t *testing.T) {
	defs := []*ports.ToolManifest{
		{
			Name:        testToolName,
			Family:      testToolFamily,
			Description: testToolName,
			Parameters: []ports.ToolParameter{
				{Name: testValueName, Type: testStringType, Required: true},
			},
			Execution: ports.ToolManifestExecution{
				Backend: ports.ToolBackendSubprocess,
				Command: &ports.ToolManifestCommand{Base: []string{testEchoBinary}},
			},
			Capability: ports.ToolManifestCapability{
				TrustClass:  testToolTrustClass,
				RiskClass:   []string{testToolRiskClass},
				EffectClass: []string{testToolEffect},
			},
		},
	}

	reg, err := BuildRegistry(defs, map[string]security.ToolPolicy{
		testToolName: {Execute: "allow"},
	}, map[string]any{
		testToolName: stubTool{name: testToolName},
	}, nil)
	require.NoError(t, err)
	tool, ok := reg.Tool("demo")
	require.True(t, ok)
	require.Equal(t, stubTool{name: testToolName}, tool)
}

