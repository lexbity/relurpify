func TestGenerateSubprocessTool_ParameterSubstitution(t *testing.T) {
	def := &ports.ToolManifest{
		Name:   testToolName,
		Family: testToolFamily,
		Parameters: []ports.ToolParameter{
			{Name: testValueName, Type: testStringType, Required: true},
		},
		Execution: ports.ToolManifestExecution{
			Backend: ports.ToolBackendSubprocess,
			Command: &ports.ToolManifestCommand{
				Base: []string{testEchoBinary},
				Args: []string{"${value}"},
			},
		},
		Capability: ports.ToolManifestCapability{
			TrustClass:  testToolTrustClass,
			RiskClass:   []string{testToolRiskClass},
			EffectClass: []string{testToolEffect},
		},
	}
	runner := &recordingRunner{}
	tool := subprocess.NewTool(*def, runner)
	result, err := tool.Execute(context.Background(), map[string]any{testValueName: "hello"})
	require.NoError(t, err)
	require.True(t, result.Success)
	require.Equal(t, []string{testEchoBinary, "hello"}, runner.request.Args)
}

func TestGenerateSubprocessTool_ExitCodeInData(t *testing.T) {
	def := &ports.ToolManifest{
		Name:   testToolName,
		Family: testToolFamily,
		Execution: ports.ToolManifestExecution{
			Backend: ports.ToolBackendSubprocess,
			Command: &ports.ToolManifestCommand{
				Base: []string{testFalseBinary},
			},
		},
		Capability: ports.ToolManifestCapability{
			TrustClass:  testToolTrustClass,
			RiskClass:   []string{testToolRiskClass},
			EffectClass: []string{testToolEffect},
		},
	}

	t.Run("non-zero exit code surfaces in Data", func(t *testing.T) {
		runner := &recordingRunner{exitCode: 1, stderr: "error occurred"}
		tool := subprocess.NewTool(*def, runner)
		result, err := tool.Execute(context.Background(), map[string]any{})
		require.NoError(t, err)
		require.False(t, result.Success)
		code, ok := result.Data["exit_code"]
		require.True(t, ok, "exit_code must be present in Data")
		require.Equal(t, 1, code)
	})

	t.Run("zero exit code surfaces exit_code=0", func(t *testing.T) {
		runner := &recordingRunner{exitCode: 0, stdout: "ok"}
		tool := subprocess.NewTool(*def, runner)
		result, err := tool.Execute(context.Background(), map[string]any{})
		require.NoError(t, err)
		require.True(t, result.Success)
		code, ok := result.Data["exit_code"]
		require.True(t, ok)
		require.Equal(t, 0, code)
	})

	t.Run("torn-down process has exit_code=-1", func(t *testing.T) {
		runner := &recordingRunner{exitCode: -1}
		tool := subprocess.NewTool(*def, runner)
		result, err := tool.Execute(context.Background(), map[string]any{})
		require.NoError(t, err)
		require.False(t, result.Success)
		code, ok := result.Data["exit_code"]
		require.True(t, ok)
		require.Equal(t, -1, code)
	})
}

func TestGenerateSubprocessTool_NoShellInjection(t *testing.T) {
	def := &ports.ToolManifest{
		Name:   testToolName,
		Family: testToolFamily,
		Parameters: []ports.ToolParameter{
			{Name: "value", Type: "string", Required: true},
		},
		Execution: ports.ToolManifestExecution{
			Backend: ports.ToolBackendSubprocess,
			Command: &ports.ToolManifestCommand{
				Base: []string{"echo"},
				Args: []string{"${value}"},
			},
		},
		Capability: ports.ToolManifestCapability{
			TrustClass:  "builtin_trusted",
			RiskClass:   []string{"execute"},
			EffectClass: []string{"external_state"},
		},
	}
	malicious := "hello; rm -rf /"
	runner := &recordingRunner{}
	tool := subprocess.NewTool(*def, runner)
	_, err := tool.Execute(context.Background(), map[string]any{"value": malicious})
	require.NoError(t, err)
	require.Len(t, runner.request.Args, 2)
	require.Equal(t, malicious, runner.request.Args[1])
}

